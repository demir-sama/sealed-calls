// Seals one real call against a deployed instance (BASE) and screenshots the whole flow (desktop).
import { chromium } from "@playwright/test";
const base = process.env.BASE ?? "http://localhost:3100";
const out = process.env.OUT ?? "/workspace/shots/live";
const b = await chromium.launch(); const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } });
const p = await ctx.newPage();
p.on("console", m => m.type() === "error" && console.log("ERR", m.text().slice(0, 300)));
await p.goto(base + "/seal", { waitUntil: "domcontentloaded" }); await p.waitForTimeout(3000);
await p.fill("#voice", "Demir");
await p.getByRole("radio", { name: "Me" }).click();
await p.fill("#claim", process.env.CLAIM ?? "ETH will be above $2,600 on Nov 9, 2026.");
await p.waitForTimeout(800);
await p.getByRole("button", { name: /Fill the rule/ }).click();
await p.fill("#deadline", "2026-11-09T12:00");
await p.locator("#p").fill(process.env.P ?? "35");
await p.waitForTimeout(800);
console.log("threshold", await p.inputValue("#th"));
await p.screenshot({ path: `${out}/seal-flow-1-filled.png`, fullPage: true });
await p.getByRole("button", { name: /Seal it into Walrus/ }).click();
await p.waitForTimeout(4000);
await p.screenshot({ path: `${out}/seal-flow-2-sealing.png` });
await p.waitForSelector("text=It’s on the record", { timeout: 150000 });
await p.waitForTimeout(2000);
await p.screenshot({ path: `${out}/seal-flow-3-sealed.png` });
await p.getByRole("link", { name: /Open the receipt/ }).click();
await p.waitForURL(/\/call\//, { timeout: 60000 });
console.log(p.url());
await p.waitForTimeout(6000);
await p.screenshot({ path: `${out}/seal-flow-4-call.png`, fullPage: true });
await b.close();
